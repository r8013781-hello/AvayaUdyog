ALTER TABLE customers ADD COLUMN phone VARCHAR(30) NULL, ADD COLUMN email VARCHAR(255) NULL, ADD COLUMN address VARCHAR(255) NULL, ADD COLUMN city VARCHAR(100) NULL, ADD COLUMN company_name VARCHAR(150) NULL, ADD COLUMN gstin VARCHAR(20) NULL, ADD COLUMN status VARCHAR(30) NOT NULL DEFAULT 'Active';

CREATE TABLE projects (
    id INTEGER GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    project_code VARCHAR(40) NOT NULL UNIQUE,
    customer_id INTEGER NOT NULL REFERENCES customers(id),
    name VARCHAR(150) NOT NULL,
    project_type VARCHAR(80) NOT NULL,
    site_address VARCHAR(255) NOT NULL,
    city VARCHAR(100) NULL,
    area_sqft DECIMAL(12,2) NULL,
    budget DECIMAL(14,2) NULL,
    stage VARCHAR(40) NOT NULL DEFAULT 'Enquiry',
    start_date DATE NULL,
    target_date DATE NULL,
    scope TEXT NULL,
    created_by INTEGER NOT NULL REFERENCES employees(id),
    created_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT CURRENT_TIMESTAMP
);

ALTER TABLE quotations ADD COLUMN project_id INTEGER NULL REFERENCES projects(id);
